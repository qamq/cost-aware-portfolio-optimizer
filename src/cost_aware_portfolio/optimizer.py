# Choose the best projected initial point among several candidates.
def _select_initial_point(
    *,
    candidates: Sequence[np.ndarray],
    w_prev: np.ndarray,
    alpha_vec: np.ndarray,
    G: np.ndarray,
    spreads_vec: np.ndarray,
    impact_coeff_vec: np.ndarray,
    params: CostAwareParams,
    target_sum: float,
    low: np.ndarray,
    high: np.ndarray,
) -> Tuple[np.ndarray, float]:
    best_w: Optional[np.ndarray] = None
    best_obj = float("inf")
    for cand in candidates:
        z = _project_sum_and_box(np.asarray(cand, dtype=float), target_sum, low, high)
        z = _apply_gross_target(z, target_sum=target_sum, low=low, high=high, params=params)
        obj = _smooth_objective(
            w=z,
            w_prev=w_prev,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
        )
        if np.isfinite(obj) and obj < best_obj:
            best_w = z.copy()
            best_obj = float(obj)

    if best_w is None:
        z = _project_sum_and_box(np.asarray(candidates[0], dtype=float), target_sum, low, high)
        z = _apply_gross_target(z, target_sum=target_sum, low=low, high=high, params=params)
        best_w = z
        best_obj = float(_smooth_objective(
            w=z,
            w_prev=w_prev,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
        ))
    return best_w, best_obj


# Solve the smooth projected problem with projected gradient, BB step guesses, and Armijo fallback.
def _projected_armijo_solve(
    *,
    w_init: np.ndarray,
    w_prev: np.ndarray,
    alpha_vec: np.ndarray,
    G: np.ndarray,
    spreads_vec: np.ndarray,
    impact_coeff_vec: np.ndarray,
    params: CostAwareParams,
    target_sum: float,
    low: np.ndarray,
    high: np.ndarray,
    warn_label: str,
) -> Tuple[np.ndarray, bool]:
    w = _project_sum_and_box(np.asarray(w_init, dtype=float), target_sum, low, high)
    w = _apply_gross_target(w, target_sum=target_sum, low=low, high=high, params=params)

    obj = _smooth_objective(
        w=w,
        w_prev=w_prev,
        alpha_vec=alpha_vec,
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
    )
    best_w = w.copy()
    best_obj = float(obj)

    grad_prev: Optional[np.ndarray] = None
    w_prev_iter: Optional[np.ndarray] = None
    step_guess = max(float(params.step), 1e-8)
    converged = False

    for _ in range(int(params.max_iters)):
        grad = _smooth_gradient(
            w=w,
            w_prev=w_prev,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
        )
        if not np.isfinite(grad).all():
            break

        inv_h0_diag = _diag_inverse_hessian0(
            w=w,
            w_prev=w_prev,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
        )
        direction = -(inv_h0_diag * grad)
        if float(np.dot(grad, direction)) >= 0.0:
            direction = -grad

        if grad_prev is not None and w_prev_iter is not None:
            s = w - w_prev_iter
            y = grad - grad_prev
            sty = float(np.dot(s, y))
            sts = float(np.dot(s, s))
            if np.isfinite(sty) and np.isfinite(sts) and sty > 1e-14 and sts > 0.0:
                bb_step = sts / sty
                if np.isfinite(bb_step):
                    step_guess = float(np.clip(bb_step, 1e-8, 1e8))

        candidate, cand_obj, step_used, accepted = _projected_armijo_line_search(
            w=w,
            direction=direction,
            grad=grad,
            obj=float(obj),
            w_prev=w_prev,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
            target_sum=target_sum,
            low=low,
            high=high,
            initial_step=step_guess,
        )
        if not accepted:
            break

        max_change = float(np.max(np.abs(candidate - w)))
        w_prev_iter = w.copy()
        grad_prev = grad.copy()
        w = candidate
        obj = float(cand_obj)
        step_guess = max(float(step_used), 1e-8)

        if np.isfinite(obj) and obj < best_obj:
            best_w = w.copy()
            best_obj = float(obj)

        if max_change < float(params.tol):
            converged = True
            break

    if not converged:
        warnings.warn(
            f"{warn_label} reached max_iters; returning best feasible iterate found.",
            RuntimeWarning,
            stacklevel=2,
        )
    return best_w, converged


# Solve the smooth projected problem with projected L-BFGS and safeguarded Armijo backtracking.
def _projected_lbfgs_solve(
    *,
    w_init: np.ndarray,
    w_prev: np.ndarray,
    alpha_vec: np.ndarray,
    G: np.ndarray,
    spreads_vec: np.ndarray,
    impact_coeff_vec: np.ndarray,
    params: CostAwareParams,
    target_sum: float,
    low: np.ndarray,
    high: np.ndarray,
    warn_label: str,
    memory: int = 10,
) -> Tuple[np.ndarray, bool, bool]:
    w = _project_sum_and_box(np.asarray(w_init, dtype=float), target_sum, low, high)
    w = _apply_gross_target(w, target_sum=target_sum, low=low, high=high, params=params)

    obj = _smooth_objective(
        w=w,
        w_prev=w_prev,
        alpha_vec=alpha_vec,
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
    )
    best_w = w.copy()
    best_obj = float(obj)

    grad = _smooth_gradient(
        w=w,
        w_prev=w_prev,
        alpha_vec=alpha_vec,
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
    )
    if not np.isfinite(grad).all():
        return best_w, False, False

    s_hist: List[np.ndarray] = []
    y_hist: List[np.ndarray] = []
    step_guess = max(float(params.step), 1e-8)
    converged = False

    for _ in range(int(params.max_iters)):
        h0_diag = _diag_inverse_hessian0(
            w=w,
            w_prev=w_prev,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
        )
        if s_hist:
            direction = _lbfgs_two_loop(
                grad=grad,
                s_hist=s_hist,
                y_hist=y_hist,
                h0_diag=h0_diag,
            )
        else:
            direction = -(h0_diag * grad)

        if (not np.isfinite(direction).all()) or float(np.dot(grad, direction)) >= 0.0:
            direction = -(h0_diag * grad)
            if float(np.dot(grad, direction)) >= 0.0:
                direction = -grad

        candidate, cand_obj, step_used, accepted = _projected_armijo_line_search(
            w=w,
            direction=direction,
            grad=grad,
            obj=float(obj),
            w_prev=w_prev,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
            target_sum=target_sum,
            low=low,
            high=high,
            initial_step=step_guess,
        )

        if not accepted:
            fallback_w, fallback_conv = _projected_armijo_solve(
                w_init=w,
                w_prev=w_prev,
                alpha_vec=alpha_vec,
                G=G,
                spreads_vec=spreads_vec,
                impact_coeff_vec=impact_coeff_vec,
                params=params,
                target_sum=target_sum,
                low=low,
                high=high,
                warn_label=f"{warn_label} fallback projected-gradient solver",
            )
            fallback_obj = _smooth_objective(
                w=fallback_w,
                w_prev=w_prev,
                alpha_vec=alpha_vec,
                G=G,
                spreads_vec=spreads_vec,
                impact_coeff_vec=impact_coeff_vec,
                params=params,
            )
            if np.isfinite(fallback_obj) and fallback_obj <= best_obj:
                return fallback_w, bool(fallback_conv), True
            break

        new_grad = _smooth_gradient(
            w=candidate,
            w_prev=w_prev,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
        )
        if not np.isfinite(new_grad).all():
            break

        s = candidate - w
        y = new_grad - grad
        sty = float(np.dot(s, y))
        if np.isfinite(sty) and sty > 1e-14:
            if len(s_hist) >= int(memory):
                s_hist.pop(0)
                y_hist.pop(0)
            s_hist.append(s.copy())
            y_hist.append(y.copy())

        max_change = float(np.max(np.abs(candidate - w)))
        w = candidate
        grad = new_grad
        obj = float(cand_obj)
        step_guess = max(float(step_used), 1e-8)

        if np.isfinite(obj) and obj < best_obj:
            best_w = w.copy()
            best_obj = float(obj)

        if max_change < float(params.tol):
            converged = True
            break

    if not converged:
        warnings.warn(
            f"{warn_label} reached max_iters; returning best feasible iterate found.",
            RuntimeWarning,
            stacklevel=2,
        )
    return best_w, converged, False


# Compute realized linear and nonlinear trading costs from a trade vector.
def compute_trade_cost_breakdown(
    *,
    w: pd.Series,
    w_prev: pd.Series,
    spreads_oneway: pd.Series,
    sigma: Optional[pd.Series] = None,
    adv: Optional[pd.Series] = None,
    aum: float = 1.0,
    impact_kappa: float = 1.0,
    impact_exponent: float = 1.5,
    execution_days: float = 1.0,
) -> TradeCostBreakdown:
    w_use = _canonical_series(w, name="w")
    w_prev_use = _canonical_series(w_prev, name="w_prev")
    spreads_use = _canonical_series(spreads_oneway, name="spreads_oneway")
    idx = pd.Index(w_use.index)
    w_cur = pd.to_numeric(w_use.reindex(idx), errors="coerce")
    w_old = pd.to_numeric(w_prev_use.reindex(idx), errors="coerce")
    spreads = pd.to_numeric(spreads_use.reindex(idx), errors="coerce")
    if w_cur.isna().any() or w_old.isna().any() or spreads.isna().any():
        raise RuntimeError("Trade cost breakdown received missing aligned inputs.")
    spreads = spreads.abs()
    delta = (w_cur - w_old).abs()
    linear_cost = float((spreads * delta).sum())

    impact_cost = 0.0
    if sigma is not None and adv is not None:
        sigma_use = _canonical_series(sigma, name="sigma")
        adv_use = _canonical_series(adv, name="adv")
        sigma_vec = pd.to_numeric(sigma_use.reindex(idx), errors="coerce")
        adv_vec = pd.to_numeric(adv_use.reindex(idx), errors="coerce")
        if sigma_vec.isna().any() or adv_vec.isna().any():
            raise RuntimeError("Trade cost breakdown received missing sigma/adv inputs.")
        sigma_vec = sigma_vec.abs()
        adv_vec = adv_vec.clip(lower=1.0)
        coeff = pd.Series(
            _impact_coeff_vector(
                sigma_vec=sigma_vec.to_numpy(dtype=float),
                adv_vec=adv_vec.to_numpy(dtype=float),
                aum=float(aum),
                impact_kappa=float(impact_kappa),
                execution_days=float(execution_days),
            ),
            index=idx,
        )
        impact_cost = float((coeff * np.power(delta.to_numpy(dtype=float), float(impact_exponent))).sum())

    return TradeCostBreakdown(
        linear_cost=float(linear_cost),
        impact_cost=float(impact_cost),
        total_cost=float(linear_cost + impact_cost),
    )


# Solve the alpha-driven nonlinear-cost objective with smooth projected gradient and backtracking.
def solve_cost_aware_nonlinear_pg(
    *,
    alpha: pd.Series,
    Sigma: np.ndarray,
    w_prev: pd.Series,
    adv: pd.Series,
    sigma: pd.Series,
    aum: float,
    spreads_oneway: Optional[pd.Series] = None,
    spreads_bps: Optional[pd.Series] = None,
    params: Optional[CostAwareParams] = None,
    desired_target_sum: Optional[float] = None,
) -> pd.Series:
    alpha_use = _canonical_series(alpha, name="alpha")
    w_prev_use = _canonical_series(w_prev, name="w_prev")
    idx = pd.Index(alpha_use.index)
    if params is None:
        params = CostAwareParams()

    alpha_aligned = pd.to_numeric(alpha_use.reindex(idx), errors="coerce")
    w_prev_aligned = pd.to_numeric(w_prev_use.reindex(idx), errors="coerce")
    if alpha_aligned.isna().any():
        raise RuntimeError("Cost-aware optimizer received missing alpha inputs after alignment.")
    if w_prev_aligned.isna().any():
        raise RuntimeError("Cost-aware optimizer received missing previous weights after alignment.")
    alpha_vec = alpha_aligned.to_numpy(dtype=float)
    w0 = w_prev_aligned.to_numpy(dtype=float)
    adv_vec = _resolve_adv_vector(idx, adv)
    sigma_vec = _resolve_sigma_vector(idx, sigma)
    spreads_vec = _resolve_spreads_fraction(
        idx,
        spreads_oneway=spreads_oneway,
        spreads_bps=spreads_bps,
        default_bps=params.spread_bps_default,
    )
    impact_coeff_vec = _impact_coeff_vector(
        sigma_vec=sigma_vec,
        adv_vec=adv_vec,
        aum=float(aum),
        impact_kappa=float(params.impact_kappa),
        execution_days=params.resolved_execution_days(),
    )

    low, high, requested_target_sum, min_sum, max_sum = _compute_bounds_stats(
        n=len(idx),
        w_prev=w0,
        adv_vec=adv_vec,
        aum=float(aum),
        params=params,
    )
    target_sum = _resolve_effective_target_sum(
        params=params,
        requested_target_sum=requested_target_sum,
        min_sum=min_sum,
        max_sum=max_sum,
        desired_target_sum=desired_target_sum,
    )

    Sigma_arr = np.asarray(Sigma, dtype=float)
    if Sigma_arr.ndim != 2 or Sigma_arr.shape[0] != Sigma_arr.shape[1]:
        raise RuntimeError(f"Cost-aware optimizer expected a square covariance matrix; got shape {Sigma_arr.shape}.")
    if Sigma_arr.shape[0] != len(idx):
        raise RuntimeError(
            f"Cost-aware optimizer received a covariance matrix of size {Sigma_arr.shape[0]} for {len(idx)} assets."
        )
    if not np.isfinite(Sigma_arr).all():
        raise RuntimeError("Cost-aware optimizer received a covariance matrix with non-finite entries.")
    Sigma_arr = 0.5 * (Sigma_arr + Sigma_arr.T)
    G = 2.0 * float(params.lambda_risk) * Sigma_arr

    if abs(target_sum) <= 1e-12 and params.long_only and not params.dollar_neutral:
        out = pd.Series(np.zeros(len(idx), dtype=float), index=idx, name="w_opt")
        out.attrs["effective_target_sum"] = float(target_sum)
        out.attrs["requested_target_sum"] = float(requested_target_sum if desired_target_sum is None else desired_target_sum)
        out.attrs["min_feasible_sum"] = float(min_sum)
        out.attrs["max_feasible_sum"] = float(max_sum)
        out.attrs["solver_method"] = "no_trade_zero_target"
        out.attrs["solver_converged"] = True
        out.attrs["solver_fallback_used"] = False
        return out

    w_init, _ = _select_initial_point(
        candidates=[w0],
        w_prev=w0,
        alpha_vec=alpha_vec,
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
        target_sum=target_sum,
        low=low,
        high=high,
    )
    solver_method = "projected_gradient"
    solver_fallback_used = False
    if _is_strongly_convex_configuration(
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
    ):
        w_best, solver_converged, solver_fallback_used = _projected_lbfgs_solve(
            w_init=w_init,
            w_prev=w0,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
            target_sum=target_sum,
            low=low,
            high=high,
            warn_label="Alpha-driven cost-aware optimizer",
        )
        solver_method = "lbfgs_to_projected_gradient" if solver_fallback_used else "lbfgs"
    else:
        warnings.warn(
            "Alpha-driven cost-aware optimizer is outside the intended strongly-convex regime; "
            "falling back to safeguarded projected gradient.",
            RuntimeWarning,
            stacklevel=2,
        )
        w_best, solver_converged = _projected_armijo_solve(
            w_init=w_init,
            w_prev=w0,
            alpha_vec=alpha_vec,
            G=G,
            spreads_vec=spreads_vec,
            impact_coeff_vec=impact_coeff_vec,
            params=params,
            target_sum=target_sum,
            low=low,
            high=high,
            warn_label="Alpha-driven cost-aware optimizer",
        )

    out = pd.Series(w_best, index=idx, name="w_opt")
    out.attrs["effective_target_sum"] = float(target_sum)
    out.attrs["requested_target_sum"] = float(requested_target_sum if desired_target_sum is None else desired_target_sum)
    out.attrs["min_feasible_sum"] = float(min_sum)
    out.attrs["max_feasible_sum"] = float(max_sum)
    out.attrs["solver_method"] = str(solver_method)
    out.attrs["solver_converged"] = bool(solver_converged)
    out.attrs["solver_fallback_used"] = bool(solver_fallback_used)
    return out


# Solve a target-tracking nonlinear rebalance problem around a fixed weight target.
def solve_rebalance_to_target_nonlinear_pg(
    *,
    w_target: pd.Series,
    w_prev: pd.Series,
    adv: pd.Series,
    sigma: pd.Series,
    aum: float,
    spreads_oneway: Optional[pd.Series] = None,
    spreads_bps: Optional[pd.Series] = None,
    params: Optional[CostAwareParams] = None,
    desired_target_sum: Optional[float] = None,
) -> pd.Series:
    target_use = _canonical_series(w_target, name="w_target")
    w_prev_use = _canonical_series(w_prev, name="w_prev")
    idx = pd.Index(target_use.index)
    if params is None:
        params = CostAwareParams()

    w_target_aligned = pd.to_numeric(target_use.reindex(idx), errors="coerce")
    w_prev_aligned = pd.to_numeric(w_prev_use.reindex(idx), errors="coerce")
    if w_target_aligned.isna().any():
        raise RuntimeError("Target-tracking optimizer received missing target weights after alignment.")
    if w_prev_aligned.isna().any():
        raise RuntimeError("Target-tracking optimizer received missing previous weights after alignment.")
    w_target_vec = w_target_aligned.to_numpy(dtype=float)
    w0 = w_prev_aligned.to_numpy(dtype=float)
    adv_vec = _resolve_adv_vector(idx, adv)
    sigma_vec = _resolve_sigma_vector(idx, sigma)
    spreads_vec = _resolve_spreads_fraction(
        idx,
        spreads_oneway=spreads_oneway,
        spreads_bps=spreads_bps,
        default_bps=params.spread_bps_default,
    )
    impact_coeff_vec = _impact_coeff_vector(
        sigma_vec=sigma_vec,
        adv_vec=adv_vec,
        aum=float(aum),
        impact_kappa=float(params.impact_kappa),
        execution_days=params.resolved_execution_days(),
    )

    low, high, requested_target_sum, min_sum, max_sum = _compute_bounds_stats(
        n=len(idx),
        w_prev=w0,
        adv_vec=adv_vec,
        aum=float(aum),
        params=params,
    )
    target_sum = _resolve_effective_target_sum(
        params=params,
        requested_target_sum=requested_target_sum,
        min_sum=min_sum,
        max_sum=max_sum,
        desired_target_sum=desired_target_sum,
    )

    target_penalty = max(float(params.target_penalty), 1e-12)
    target_total = float(np.nansum(w_target_vec))
    if target_total < 0:
        raise RuntimeError("Target-tracking optimizer received a target portfolio with negative total weight.")

    if target_sum <= 1e-12:
        scaled_target = np.zeros(len(idx), dtype=float)
    elif target_total <= 0 or not np.isfinite(target_total):
        scaled_target = np.full(len(idx), target_sum / max(len(idx), 1), dtype=float)
    else:
        scaled_target = w_target_vec * (float(target_sum) / target_total)

    G = target_penalty * np.eye(len(idx), dtype=float)
    alpha_vec = target_penalty * scaled_target

    w_init, _ = _select_initial_point(
        candidates=[w0, scaled_target],
        w_prev=w0,
        alpha_vec=alpha_vec,
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
        target_sum=target_sum,
        low=low,
        high=high,
    )
    w_best, solver_converged = _projected_armijo_solve(
        w_init=w_init,
        w_prev=w0,
        alpha_vec=alpha_vec,
        G=G,
        spreads_vec=spreads_vec,
        impact_coeff_vec=impact_coeff_vec,
        params=params,
        target_sum=target_sum,
        low=low,
        high=high,
        warn_label="Target-tracking cost-aware optimizer",
    )

    out = pd.Series(w_best, index=idx, name="w_opt")
    out.attrs["effective_target_sum"] = float(target_sum)
    out.attrs["requested_target_sum"] = float(requested_target_sum if desired_target_sum is None else desired_target_sum)
    out.attrs["min_feasible_sum"] = float(min_sum)
    out.attrs["max_feasible_sum"] = float(max_sum)
    out.attrs["solver_method"] = "projected_gradient"
    out.attrs["solver_converged"] = bool(solver_converged)
    out.attrs["solver_fallback_used"] = False
    return out


